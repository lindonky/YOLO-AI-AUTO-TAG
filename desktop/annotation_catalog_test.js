'use strict';
const assert=require('node:assert/strict');
const {Catalog,classified}=require('../annotation_catalog');
const ReviewState=require('../review_state');
const box=name=>({label:name,box_2d:[100,200,400,500]});
const s={unifiedClassMap:new Map(),nextClassId:0,imageResults:[{annotations:[box('green'),box('blue')],reviewCategory:'normal',needsReview:false,validation:{status:'detected'}},{annotations:[box('green')],reviewCategory:'normal'}],videoResults:[{annotations:[box('green')]}],teachingExamples:[{boxes:[box('green')]}],teachingDraftBoxes:[box('green')],annotations:[box('green')]};
const input={value:'blue green'},catalog=new Catalog(()=>s,()=>input,()=>ReviewState);
assert.deepEqual(catalog.ensure(),['blue','green']);
const rename=catalog.edit({kind:'rename',from:'green',to:'cube'});
assert.ok(catalog.groups().every(g=>g.owner[g.key].every(b=>b.label!=='green')));
assert.deepEqual(catalog.labels(),['blue','cube']);assert.equal(input.value,'blue cube');
rename.undo();assert.equal(s.imageResults[1].annotations[0].label,'green');rename.redo();
const before=JSON.stringify(s.imageResults);
const removal=catalog.edit({kind:'delete',from:'cube'});
assert.equal(s.imageResults[0].annotations.length,2);
assert.ok(ReviewState.validGeometry(s.imageResults[0].annotations[0]));
assert.equal(ReviewState.validBox(s.imageResults[0].annotations[0]),false);
assert.equal(s.imageResults[0].reviewCategory,'error');assert.equal(s.imageResults[0].needsReview,true);
assert.equal(s.teachingExamples[0].boxes[0].unclassified,true);
assert.deepEqual(catalog.ensure(),['blue']);assert.equal(s.nextClassId,1);
const addition=catalog.edit({kind:'add',to:'cube'});
assert.equal(classified(s.imageResults[1].annotations[0]),false,'Re-adding the name must not silently classify old boxes');
addition.undo();removal.undo();assert.equal(JSON.stringify(s.imageResults),before);
assert.throws(()=>catalog.edit({kind:'rename',from:'cube',to:'blue'}),/已存在/);
assert.throws(()=>catalog.edit({kind:'add',to:'未分类'}),/保留名称/);
s.isProcessing=true;assert.throws(()=>catalog.edit({kind:'delete',from:'cube'}),/先结束/);s.isProcessing=false;
const legacy=[{annotations:[box('orange'),box('blue')]}];catalog.restore({classLabel:'green blue'},legacy);
assert.deepEqual(catalog.labels(),['green','blue','orange'],'Legacy labels keep their declared order, then inferred classes');
const modern=[{annotations:[box('removed'),box('blue'),{...box(''),unclassified:true,previousLabel:'green'}]}];
catalog.restore({classes:['blue','new'],classLabel:'wrong stale input'},modern);
assert.deepEqual(catalog.labels(),['blue','new']);assert.equal(modern[0].annotations[0].unclassified,true);
assert.equal(modern[0].annotations[0].previousLabel,'removed');assert.equal(modern[0].annotations.length,3);
console.log('Global label rename/delete, geometry preservation, reversible edits and V1.2.5 migration: passed');
